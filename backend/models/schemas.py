# Pydantic models for request/response schemas

from typing import List, Optional
from pydantic import BaseModel, Field


class RecommendationRequest(BaseModel):
    """
    Input schema for incoming POST requests from the React frontend.
    """

    query: str = Field(
        ...,
        description="Natural language query from user describing desired restaurant/cuisine",
        example="Casual Mexican Spot in 19103 with outdoor seating"
    )

    top_k: Optional[int] = Field(
        default=5,
        ge=1,
        le=20,
        description="Number of vector records to retrieve from Pinecone"
    )

    postal_code: Optional[str] = Field(
        default=None,
        description="Optional 5-digit zip code filter"
    )

class RestaurantCard(BaseModel):
    """
    Structured schema representing an individual restaurant retrieved from Pinecone.
    """

    restaurant_name: str
    full_address: str
    postal_code: str
    review_stars: float
    categories: List[str] = []
    features: List[str] = []
    review_text: str
    score: float = Field(..., description="Cosine similarity score from Pinecone (0.0 to 1.0)")

class RecommendationResponse(BaseModel):
    """
    Output schema sent back to the React frontend.
    """

    query: str
    recommendation: str = Field(..., description="Conversational synthesis response generated by GPT-4o")
    restaurants: List[RestaurantCard]  = Field(
        default_factory = list,
        description="List of structured restaurant cards matching the query"
    )